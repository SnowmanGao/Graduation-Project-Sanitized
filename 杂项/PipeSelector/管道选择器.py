def select_pipe(required_inner_diameter: float,
                pipes: Dict[float, List[float]] = PIPE_OPTIONS) -> Optional[Tuple[float, float, float]]:
    """
    选管规则：
    - 允许 向上圆整 / 向下圆整
    - 直接选择“实际内径与需求内径差值最小”的方案（绝对值最小）

    返回:
        (外径, 壁厚, 实际内径)
    """
    candidates = []

    for od, thks in pipes.items():
        for t in thks:
            actual_id = round(od - 2 * t, 3)
            candidates.append((od, t, actual_id))

    if not candidates:
        return None

    # 绝对差值最小优先
    # 次级：外径小、壁厚小（一般更经济）
    candidates.sort(key=lambda x: (abs(x[2] - required_inner_diameter), x[0], x[1]))

    return candidates[0]


